def test_jpeg_artifacts_true_and_false_color(tmp_path):
    import extract_chips

    scene = make_fixture_tif(tmp_path / "S2A_JPEG")
    out = tmp_path / "thumbs"
    chips = extract_chips.extract_chips(
        scene_dir=scene, out_dir=out, chip_size=512, stride=512
    )
    cid = chips[0]["chip_id"]
    window = Window(0, 0, 512, 512)
    b04 = read_window(scene / "B04.tif", window)
    b08 = read_window(scene / "B08.tif", window)

    tc = read_jpeg(out / f"{cid}.jpg")
    fc = read_jpeg(out / f"{cid}_fc.jpg")
    assert tc.shape == (3, 512, 512)
    assert fc.shape == (3, 512, 512)
    assert (out / f"{cid}.jpg").read_bytes()[:2] == b"\xff\xd8"  # JPEG magic
    # true-color R channel comes from B04; false-color R channel from NIR B08
    # (JPEG is lossy -> mean-absolute-error tolerance)
    assert np.abs(tc[0].astype(np.int16) - extract_chips.to_uint8(b04).astype(np.int16)).mean() < 8
    assert np.abs(fc[0].astype(np.int16) - extract_chips.to_uint8(b08).astype(np.int16)).mean() < 8
    assert not np.array_equal(tc, fc)  # Option B: true/false previews differ


def test_true_false_color_band_order_and_uint8_stretch():
    import extract_chips

    # one *distinct gradient shape* per band: the per-channel percentile
    # stretch is shift/scale invariant (a*x+b -> same output), so only
    # content shape makes a swapped channel fail these pins
    row = np.repeat(np.arange(64, dtype=np.float32)[:, None], 64, axis=1)
    col = np.repeat(np.arange(64, dtype=np.float32)[None, :], 64, axis=0)
    b02 = col.astype(np.uint16)                    # horizontal
    b03 = row.astype(np.uint16)                    # vertical
    b04 = (col + row).astype(np.uint16)            # diagonal
    b08 = np.abs(col - row).astype(np.uint16)      # V

    tc = extract_chips.true_color(b04, b03, b02)  # B04/B03/B02 -> R/G/B
    assert tc.shape == (3, 64, 64) and tc.dtype == np.uint8
    # each channel is exactly its band's stretch — band order pinned
    assert np.array_equal(tc[0], extract_chips.to_uint8(b04))
    assert np.array_equal(tc[1], extract_chips.to_uint8(b03))
    assert np.array_equal(tc[2], extract_chips.to_uint8(b02))
    assert not np.array_equal(tc[0], extract_chips.to_uint8(b02))  # R is not B02

    fc = extract_chips.false_color(b08, b04, b03)  # NIR-R-G
    assert np.array_equal(fc[0], extract_chips.to_uint8(b08))
    assert np.array_equal(fc[1], extract_chips.to_uint8(b04))
    assert np.array_equal(fc[2], extract_chips.to_uint8(b03))
    assert not np.array_equal(fc[0], extract_chips.to_uint8(b04))  # NIR is not red

    # constant (nodata) chip: no divide-by-zero, deterministic output
    flat = extract_chips.to_uint8(np.full((8, 8), 1234, np.uint16))
    assert flat.dtype == np.uint8 and flat.min() == flat.max()
    assert extract_chips.to_uint8(np.zeros((8, 8), np.uint16)).max() == 0


