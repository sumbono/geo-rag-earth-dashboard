def test_golden_four_chips_bbox_and_stable_ids(tmp_path):
    import extract_chips

    scene = make_fixture_tif(
        tmp_path / "S2A_FIXTURE_20261004_0_L2A", transform=GOLDEN_TRANSFORM
    )
    out = tmp_path / "thumbs"
    chips = extract_chips.extract_chips(
        scene_dir=scene, out_dir=out, chip_size=512, stride=512
    )

    # 1024 / 512 at stride 512 -> exactly 4 chips (2x2 grid)
    assert len(chips) == 4

    # chip 0 bbox within 1e-6 of the transform-derived corners
    wt = window_transform(Window(0, 0, 512, 512), GOLDEN_TRANSFORM)
    corners = [wt @ (0, 0), wt @ (512, 0), wt @ (512, 512), wt @ (0, 512)]
    xs, ys = zip(*corners)
    expected = (min(xs), min(ys), max(xs), max(ys))
    assert all(abs(a - b) <= 1e-6 for a, b in zip(chips[0]["bbox"], expected))
    assert chips[0]["bbox"] == pytest.approx(GOLDEN_CHIP0_BBOX, abs=1e-6)
    # row-stride math: index 2 is (row=512, col=0) — one full chip further south
    assert chips[2]["bbox"] == pytest.approx(
        (39.0, 21.8976, 39.0512, 21.9488), abs=1e-6
    )

    # three artifacts per chip: true-color jpg, false-color jpg, 4-band npy
    # in the sibling cache dir (npy lives beside thumbs/, not inside it)
    cid = chips[0]["chip_id"]
    assert (out / f"{cid}.jpg").is_file()
    assert (out / f"{cid}_fc.jpg").is_file()
    npy = np.load(tmp_path / "chips" / f"{cid}.npy")
    assert npy.shape == (4, 512, 512)
    assert npy.dtype == np.float32
    window = Window(0, 0, 512, 512)
    stack = [read_window(scene / f"{band}.tif", window) for band in BANDS]
    assert np.array_equal(npy, np.stack(stack).astype(np.float32))  # B02,B03,B04,B08

    # chip_id = uuid5(scene_id + row + col), deterministic across runs
    assert cid == str(uuid.uuid5(extract_chips.CHIP_NAMESPACE, f"{scene.name}:0:0"))

    # chips_manifest.jsonl — the artifact Task 13 consumes
    lines = [
        json.loads(line)
        for line in (out / "chips_manifest.jsonl").read_text().splitlines()
    ]
    assert len(lines) == 4
    assert lines[0]["chip_id"] == cid
    assert lines[0]["scene_datetime"] == "2026-10-04T08:04:23.747000Z"  # scene.json
    assert Path(lines[0]["chip_path"]).name == f"{cid}.jpg"  # Task 13 thumb basename
    assert Path(lines[0]["chip_path"]).is_absolute()
    assert Path(lines[0]["npy_path"]).is_file()
    assert lines[0]["bbox"] == pytest.approx(list(GOLDEN_CHIP0_BBOX), abs=1e-6)

    # served dir is clean: jpgs + fc jpgs + manifest only (no .aux.xml sidecars)
    expected_files = {f"{c['chip_id']}{s}" for c in chips for s in (".jpg", "_fc.jpg")}
    expected_files.add("chips_manifest.jsonl")
    assert {p.name for p in out.iterdir()} == expected_files

    # chip_id stable across a second run; manifest append dedupes by chip_id
    again = extract_chips.extract_chips(
        scene_dir=scene, out_dir=out, chip_size=512, stride=512
    )
    assert [c["chip_id"] for c in again] == [c["chip_id"] for c in chips]
    assert len((out / "chips_manifest.jsonl").read_text().splitlines()) == 4


