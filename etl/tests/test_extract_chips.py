def test_scene_urls_primary_path_windowed_vsicurl_reads(tmp_path, monkeypatch):
    import extract_chips

    # local stand-in data; the seam open_band is patched to serve it
    fixture = make_fixture_tif(tmp_path / "fixture_src")
    scene_id = "S2A_37QDD_20261004_0_L2A"
    root = (
        "https://sentinel-cogs.s3.us-west-2.amazonaws.com/"
        f"sentinel-s2-l2a-cogs/37/Q/DD/2026/10/{scene_id}"
    )
    urls = {b: f"{root}/{b}.tif" for b in BANDS}

    opened = []
    real_open = extract_chips.open_band

    def fake_open(path):
        opened.append(path)
        band = Path(path[len("/vsicurl/") :]).stem
        return real_open(fixture / f"{band}.tif")

    monkeypatch.setattr(extract_chips, "open_band", fake_open)
    chips = extract_chips.extract_chips(
        scene_urls=urls, out_dir=tmp_path / "thumbs", chip_size=512, stride=512
    )
    assert len(chips) == 4
    assert len(opened) == 4  # one open per band, windowed reads inside
    assert all(p.startswith("/vsicurl/https://") for p in opened)

    # scene id derived from the URL's scene directory; ids deterministic
    assert chips[0]["chip_id"] == str(
        uuid.uuid5(extract_chips.CHIP_NAMESPACE, f"{scene_id}:0:0")
    )
    assert chips[3]["chip_id"] == str(
        uuid.uuid5(extract_chips.CHIP_NAMESPACE, f"{scene_id}:512:512")
    )
    # no scene.json over HTTP -> day-precision date from the scene id
    assert chips[0]["scene_datetime"] == "2026-10-04T00:00:00Z"


def test_unsigned_mpc_blob_url_logs_error_and_skips(tmp_path, monkeypatch, caplog):
    """MPC-primary manifests carry UNSIGNED blob hrefs (GET -> HTTP 409).

    The extractor must fail with a clear ERROR pointing at re-signing, not a
    cryptic rasterio failure deep inside /vsicurl/.
    """
    import extract_chips

    scene_id = "S2C_MSIL2A_20261004T074731_R135_T37QDD_20261004T110813"
    root = (
        "https://sentinel2l2a01.blob.core.windows.net/"
        f"sentinel2-l2/37/Q/DD/2026/10/{scene_id}"
    )
    urls = {b: f"{root}/{b}.tif" for b in BANDS}  # no SAS sig= -> 409

    def _boom(path):
        raise AssertionError("unsigned blob href must be gated before rasterio opens it")

    monkeypatch.setattr(extract_chips, "open_band", _boom)
    with caplog.at_level(logging.ERROR):
        chips = extract_chips.extract_chips(
            scene_urls=urls, out_dir=tmp_path / "thumbs", chip_size=512, stride=512
        )
    assert chips == []
    assert any("409" in m and "sign" in m.lower() for m in caplog.messages)

    # control: the same hrefs WITH a SAS signature pass the gate and extract
    fixture = make_fixture_tif(tmp_path / "signed_src")
    signed = {b: urls[b] + "?se=2026-10-07T07:00:00Z&sp=rl&sig=deadbeef" for b in BANDS}
    real_open = rasterio.open

    def fake_open(path):
        band = Path(path[len("/vsicurl/") :].split("?")[0]).stem
        return real_open(fixture / f"{band}.tif")

    monkeypatch.setattr(extract_chips, "open_band", fake_open)
    chips = extract_chips.extract_chips(
        scene_urls=signed, out_dir=tmp_path / "t2", chip_size=512, stride=512
    )
    assert len(chips) == 4


