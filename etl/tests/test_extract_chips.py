"""Tests for etl/extract_chips.py (Task 12) — golden-file chip extraction.

Run from ``etl/``:

    ../.venv/bin/pytest -v            # deterministic, offline

Golden test (brief Step 1): a synthetic 1024x1024 GeoTIFF generated by
``make_fixture_tif.py`` (no binary fixtures in git), chip_size=512 stride=512
-> exactly 4 chips; chip 0 bbox within 1e-6 of the transform-derived corners;
chip_id stable across two runs.
"""
import json
import logging
import uuid
import warnings
from pathlib import Path

import numpy as np
import pytest
import rasterio
from rasterio.errors import NotGeoreferencedWarning
from rasterio.transform import from_origin
from rasterio.windows import Window
from rasterio.windows import transform as window_transform

from make_fixture_tif import BANDS, make_fixture_tif

GOLDEN_TRANSFORM = from_origin(39.0, 22.0, 0.0001, 0.0001)
# literal corners of window (0, 0, 512, 512) under GOLDEN_TRANSFORM
GOLDEN_CHIP0_BBOX = (39.0, 21.9488, 39.0512, 22.0)


def read_jpeg(path):
    """Read a thumbnail, silencing the benign NotGeoreferencedWarning (JPEGs carry no georef)."""
    with warnings.catch_warnings():
        warnings.filterwarnings("ignore", category=NotGeoreferencedWarning)
        with rasterio.open(path) as src:
            return src.read()


def read_window(path, window):
    with rasterio.open(path) as src:
        return src.read(1, window=window)


