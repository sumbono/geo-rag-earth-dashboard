def test_utm_scene_bbox_reprojected_to_wgs84(tmp_path):
    from rasterio.warp import transform as warp_transform

    import extract_chips

    utm = from_origin(500000.0, 2400000.0, 10.0, 10.0)  # UTM 37N, 10 m/px
    scene = make_fixture_tif(tmp_path / "S2A_UTM", crs="EPSG:32637", transform=utm)
    chips = extract_chips.extract_chips(
        scene_dir=scene, out_dir=tmp_path / "thumbs", chip_size=512, stride=512
    )
    w, s, e, n = chips[0]["bbox"]
    lons, lats = warp_transform(
        "EPSG:32637",
        "EPSG:4326",
        [500000.0, 505120.0, 505120.0, 500000.0],
        [2400000.0, 2400000.0, 2394880.0, 2394880.0],
    )
    assert w == pytest.approx(min(lons), abs=1e-6)
    assert e == pytest.approx(max(lons), abs=1e-6)
    assert s == pytest.approx(min(lats), abs=1e-6)
    assert n == pytest.approx(max(lats), abs=1e-6)
    assert -180 < w < e < 180 and -90 < s < n < 90  # degrees, never metres


