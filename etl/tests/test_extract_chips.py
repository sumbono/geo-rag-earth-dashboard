def test_missing_band_skips_scene_with_warning(tmp_path, monkeypatch, caplog):
    import extract_chips

    scene = make_fixture_tif(tmp_path / "S2A_NO_NIR", bands=("B02", "B03", "B04"))
    out = tmp_path / "thumbs"
    with caplog.at_level(logging.WARNING):
        chips = extract_chips.extract_chips(
            scene_dir=scene, out_dir=out, chip_size=512, stride=512
        )
    assert chips == []
    assert any("S2A_NO_NIR" in m and "B08" in m for m in caplog.messages)
    assert not out.exists()  # nothing written for a skipped scene

    # same contract on the URL path (band absent from the assets dict)
    def _boom(path):
        raise AssertionError("missing-band scene must never open a dataset")

    monkeypatch.setattr(extract_chips, "open_band", _boom)
    urls = {
        b: f"https://sentinel-cogs.s3.us-west-2.amazonaws.com/x/S2A_NO_NIR/{b}.tif"
        for b in ("B02", "B03", "B04")
    }
    with caplog.at_level(logging.WARNING):
        chips = extract_chips.extract_chips(
            scene_urls=urls, out_dir=out, chip_size=512, stride=512
        )
    assert chips == []
    assert any("B08" in m for m in caplog.messages)


