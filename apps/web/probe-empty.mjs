import { chromium } from "playwright";
import path from "node:path";
const BASE = "https://geo.sumbono.dev";
const OUT = process.env.PLAY_OUT;
const b = await chromium.launch({ headless: true, args: ["--no-sandbox"] });
const p = await (await b.newContext({ viewport: { width: 1400, height: 900 } })).newPage();
await p.goto(BASE + "/login");
await p.getByLabel("Username").fill("demo");
await p.getByLabel("Password").fill("demo-pass-123");
await p.getByRole("button", { name: "Log in", exact: true }).click();
await p.waitForURL(/\/dashboard$/);
await p.getByRole("searchbox", { name: "Search" }).waitFor();
// Zoom all the way out (world view), then polygon-draw a small ring in the South Pacific
const canvas = p.locator(".maplibregl-canvas");
await canvas.waitFor();
for (let i = 0; i < 8; i++) await p.mouse.wheel(0, 3000);
await p.waitForTimeout(1500);
await p.getByRole("button", { name: "Draw polygon" }).click();
const box = await canvas.boundingBox();
await canvas.click({ position: { x: box.width * 0.18, y: box.height * 0.75 } });
await p.getByRole("status").filter({ hasText: /^1 vertex —/ }).first().waitFor({ timeout: 10000 });
await canvas.click({ position: { x: box.width * 0.24, y: box.height * 0.78 } });
await canvas.click({ position: { x: box.width * 0.21, y: box.height * 0.83 } });
const req = p.waitForResponse((r) => r.url().includes("/api/search/polygon"), { timeout: 30000 });
await p.keyboard.press("Enter");
const res = await req;
const body = await res.json().catch(() => null);
console.log("polygon →", res.status(), "results:", body?.results?.length ?? "?");
await p.waitForTimeout(1200);
const text = (await p.locator("main").innerText()).replace(/\s+/g, " ");
console.log("UI:", JSON.stringify(text.slice(0, 400)));
await p.screenshot({ path: path.join(OUT, "b03-empty-polygon-state.png") });
await b.close();
